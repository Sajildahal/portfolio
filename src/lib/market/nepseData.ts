/**
 * Generates deterministic realistic OHLCV historical candle series for any symbol
 */
export function generateHistoricalCandles(symbol: string, days: number = 60) {
  const stock = INITIAL_MARKET_PRICES.find((s) => s.symbol === symbol) || INITIAL_MARKET_PRICES[0];
  const basePrice = stock.ltp;
  const candles = [];
  const now = new Date();

  // Pseudo-random deterministic seed from symbol characters
  let seed = symbol.split("").reduce((acc, char) => acc + char.charCodeAt(0), 100);
  function pseudoRandom() {
    seed = (seed * 9301 + 49297) % 233280;
    return seed / 233280;
  }

  let currentClose = basePrice * (1 - (days * 0.003));

  for (let i = days; i >= 0; i--) {
    const date = new Date(now);
    date.setDate(date.getDate() - i);
    // Skip Saturdays (NEPSE is closed Friday/Saturday or Saturday/Sunday depending on calendar)
    const dayOfWeek = date.getDay();
    if (dayOfWeek === 6) continue; // Saturday NEPSE closed

    const drift = (pseudoRandom() - 0.48) * 0.035; // Slight bullish bias
    const open = Math.round(currentClose * (1 + (pseudoRandom() - 0.5) * 0.008) * 10) / 10;
    const close = Math.round(open * (1 + drift) * 10) / 10;
    const high = Math.round(Math.max(open, close) * (1 + pseudoRandom() * 0.018) * 10) / 10;
    const low = Math.round(Math.min(open, close) * (1 - pseudoRandom() * 0.018) * 10) / 10;
    const volume = Math.floor(stock.volume * (0.6 + pseudoRandom() * 1.2));
    const turnover = Math.round(volume * close);

    candles.push({
      date: date.toISOString().split("T")[0],
      open,
      high,
      low,
      close,
      volume,
      turnover,
    });

    currentClose = close;
  }

  // Ensure last candle matches current LTP
  if (candles.length > 0) {
    candles[candles.length - 1].close = stock.ltp;
  }

  return candles;
}
